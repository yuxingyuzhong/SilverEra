#pragma once
//============================================================================
// 前置头文件包含（系统层预编译头）
//============================================================================
// 位置：系统层/common/前置头文件包含.h
//
// 为什么系统层需要自己这一份
//     系统层源码统一写 #include "common/前置头文件包含.h"。系统层根目录在
//     包含路径里排在引擎层前面，所以这一份会优先命中，成为系统层的预编译头。
//
//     系统层需要的不只是引擎层那些东西，还要有 Sol2（sol::）——Sol2 已经由
//     引擎层搬到 系统层/external/Sol2，引擎层那份预编译头里自然没有它。
//     本层 common/external/Sol2/ 下的类型别名与类型注册头文件只 include 了
//     预编译头就直接使用 sol::table / sol::state，于是「谁提供 sol」这件事
//     必须由本层这份预编译头兜住。
//
//     做法：先整体吃下引擎层那份（保持单一真源，避免两份清单各自漂移），
//     再补上本层额外需要的外部库。
//
// 关于下面那条相对路径
//     引擎层那份不能写成 "common/前置头文件包含.h"：那会命中本文件自己。
//     这里用相对包含直接指到同级目录下的引擎层，依赖的正是「两层目录同级」
//     这一既有约定（CMake 侧定位引擎层用的也是同一个约定）。
//============================================================================

// 引擎层的通用前置包含（C/C++ 标准库、nlohmann json、GLFW、windows）
#include "../../引擎层/common/前置头文件包含.h"

//============================================================================
// 本层额外需要的
//============================================================================
// Sol2 —— Lua 绑定库（纯头文件）。本层 common/external/Sol2/ 下的
// sol类型别名.h / sol类型注册.h 会直接使用 sol::table / sol::function /
// sol::state 等类型，所以这里必须有它。
// 对应的包含路径（external/Sol2/include、external/Lua）由
// cmake/对外接口.cmake 声明，SystemCore 与上层用的是同一份声明。
#include <sol/sol.hpp>
