#pragma once
//============================================================================
// 引擎日志屏蔽 —— 把引擎日志从标准输出分流到日志文件
// ---------------------------------------------------------------------------
// 位置：白银纪元/测试层/src/主调/引擎日志屏蔽.h
// 职责：测试运行期间把引擎日志（Log）从控制台分离出去，避免与 googletest 的输出
//       交织在同一位置导致测试结果不可读。
// 做法：使用日志系统的路径节点绑定机制，把根节点 "" 绑到日志文件 —— 全部调用处的
//       日志沿父链继承该流，不再落到控制台兜底输出目标。
// 用法：主程序在进入测试前调用 日志屏蔽_开启()；
//       日志系统用例自身要验证「未绑定即走控制台」，故须成对使用
//       日志屏蔽_关闭() / 日志屏蔽_开启()（见 日志系统测试.cpp 夹具）。
//============================================================================
#include <string>

//引擎命名空间
namespace engine
{
    //屏蔽开启：把日志根节点绑定到屏蔽用日志文件（重复调用幂等）
    void 日志屏蔽_开启(void);

    //屏蔽关闭：清除根节点绑定，使引擎日志回落到控制台（供日志系统用例使用）
    void 日志屏蔽_关闭(void);

    //屏蔽日志文件路径获取（UTF-8 文本，便于诊断打印与用例断言）
    std::string 日志屏蔽_文件路径获取(void);

    //屏蔽日志落盘：把引擎日志缓冲写出并刷新（测试结束前调用，文件输出目标按阈值批量落盘）
    void 日志屏蔽_落盘(void);
}