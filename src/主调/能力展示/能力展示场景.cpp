	uint32_t 能力展示场景::展区数量(void) const
	{
		uint32_t 数量 = 0;
		展示::展区表(数量);
		return 数量;
	}

	//展区标题
	const char* 能力展示场景::展区标题(uint32_t 序号) const
	{
		uint32_t 数量 = 0;
		const 展示::展区项* 表 = 展示::展区表(数量);
		//越界返回空串
		if (序号 >= 数量)
			return "";
		return 表[序号].标题;
	}
