	//搭建场景与全部资源
	bool 能力展示场景::init(Renderer& 渲染器)
	{
		//资源台账（网格 / 纹理 / 管线 / 材质 / 目标 / 字体）
		if (!资源构建(资源_, 渲染器))
			return false;
		//相机、光照、雾、天空、阴影、簇灯墙与粒子预配置
		场景配置(资源_, 状态_, 渲染器);
		return true;
	}

	//按输入推进相机，并在窗口尺寸变化时重建中间目标
	void 能力展示场景::update(Renderer& 渲染器, const 展示输入& 输入, float 秒)
	{
		//累计时间（驱动轻量动画）
		状态_.累计秒 += 秒;
		//窗口尺寸变化：中间目标必须与交换链同尺寸
		const uint32_t 宽 = 渲染器.extent_width();
		const uint32_t 高 = 渲染器.extent_height();
		if (宽 != 资源_.目标宽 || 高 != 资源_.目标高)
		{
			if (宽 != 0 && 高 != 0)
			{
				//先建新目标、再销毁旧目标，避免中途回落单级路径
				uint64_t 新甲 = 0;
				uint64_t 新乙 = 0;
				if (渲染器.render_target_create(新甲, 宽, 高) && 渲染器.render_target_create(新乙, 宽, 高))
				{
					if (资源_.目标甲 != 0)
						渲染器.render_target_destroy(资源_.目标甲);
					if (资源_.目标乙 != 0)
						渲染器.render_target_destroy(资源_.目标乙);
					资源_.目标甲 = 新甲;
					资源_.目标乙 = 新乙;
					资源_.目标宽 = 宽;
					资源_.目标高 = 高;
				}
			}
		}

		//鼠标拖拽改变朝向（俯仰限制在 ±1.35 弧度）
		状态_.偏航 += 输入.偏航增量;
		状态_.俯仰 += 输入.俯仰增量;
		if (状态_.俯仰 > 1.35f)
			状态_.俯仰 = 1.35f;
		if (状态_.俯仰 < -1.35f)
			状态_.俯仰 = -1.35f;
		//速度（默认 8 单位 / 秒，滚轮倍率 0.25..4）
		float 速度 = 8.0f * (输入.速度倍率 > 0.0f ? 输入.速度倍率 : 1.0f);
		//前向（水平）与右向
		const float 前x = std::sin(状态_.偏航);
		const float 前z = -std::cos(状态_.偏航);
		const float 右x = std::cos(状态_.偏航);
		const float 右z = std::sin(状态_.偏航);
		//位移（WASD ＋ Q/E 升降）
		状态_.位置[0] += (前x * 输入.前后 + 右x * 输入.左右) * 速度 * 秒;
		状态_.位置[1] += 输入.上下 * 速度 * 秒;
		状态_.位置[2] += (前z * 输入.前后 + 右z * 输入.左右) * 速度 * 秒;
		//不离地过低
		if (状态_.位置[1] < 0.6f)
			状态_.位置[1] = 0.6f;
		//注视点 = 位置 ＋ 朝向（含俯仰）
		const float cos俯仰 = std::cos(状态_.俯仰);
		const float 注视x = 状态_.位置[0] + 前x * cos俯仰;
		const float 注视y = 状态_.位置[1] + std::sin(状态_.俯仰);
		const float 注视z = 状态_.位置[2] + 前z * cos俯仰;
		渲染器.camera_position_set(状态_.位置[0], 状态_.位置[1], 状态_.位置[2]);
		渲染器.camera_target_set(注视x, 注视y, 注视z);

		//进区开关（各展区的全局参数切换）
		展示::更新进区开关(资源_, 状态_, 渲染器);
	}

	/*
	探测 / 跳转用：直接设置相机位姿
	只改内部状态，渲染器相机与进区开关在随后的 update 里统一提交（与交互路径完全同源）。
	*/
	void 能力展示场景::相机位姿设置(const float 位置[3], float 偏航值, float 俯仰值)
	{
		状态_.位置[0] = 位置[0];
		//离地高度不低于 0.6（与 update 的钳制一致）
		状态_.位置[1] = 位置[1] < 0.6f ? 0.6f : 位置[1];
		状态_.位置[2] = 位置[2];
		状态_.偏航 = 偏航值;
		//俯仰钳到 ±1.35 弧度
		状态_.俯仰 = 俯仰值 > 1.35f ? 1.35f : (俯仰值 < -1.35f ? -1.35f : 俯仰值);
	}

