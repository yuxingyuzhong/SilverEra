#pragma once
/*
渲染能力展示场景（测试层入口专用，非 gtest 用例）
用途：把渲染层当前可提供的全部能力铺进**一个静态场景**，供人自由漫游观察；
      入口由图形操作界面上的按钮或命令行 --selector=showcase 提供。

本版（第三百九十九轮重构）：实现文件已拆分到 `src/主调/能力展示/` 目录：
  · 能力展示场景.cpp —— 生命周期骨架（init / update / frame_draw / shutdown）
  · 展区公共.cpp     —— 23 个展区表、地面 / 地台 / 角柱 / 三维标签、字体与像素工具
  · 资源构建.cpp     —— 网格 / 纹理 / 管线 / 材质 / 目标 / 字体
  · 场景光照.cpp     —— 相机 / 光照 / 雾 / 天空 / 阴影 / 簇灯墙 / 粒子预配置
  · 展区_*.cpp       —— 各展区绘制与进区开关（按能力域分文件）

维护约定：渲染层新增能力时，在对应 `展区_*.cpp` 里补绘制，并在 `展区公共.cpp` 的展区表补一项；
          叠加层的能力图例由展区表自动生成，无需另改界面代码。
*/
#include <cstdint>

//场景数据（相机 / 光照 / 雾；Vulkan-free，供进区重登记使用）
#include "Engine/EngineSystem/src/core/Renderer/src/render/Scene/场景数据.h"

//引擎命名空间
namespace engine
{
	//渲染器门面（仅前置声明，本头不引入任何 Vulkan / SDL 类型）
	class Renderer;

	//一帧的相机输入（由界面层从 ImGui IO 采集后传入）
	struct 展示输入
	{
		//前后 / 左右 / 上下移动量（−1..1）
		float 前后 = 0.0f;
		float 左右 = 0.0f;
		float 上下 = 0.0f;
		//鼠标拖拽造成的偏航 / 俯仰增量（弧度）
		float 偏航增量 = 0.0f;
		float 俯仰增量 = 0.0f;
		//速度倍率（滚轮调节；默认 1）
		float 速度倍率 = 1.0f;
	};

	/*
	展示资源台账（全部由 `资源构建.cpp` 创建、`shutdown` 统一释放）
	句柄 0 表示未创建（部分能力在设备不支持时为 0，绘制处按 0 判定跳过）。
	*/
	struct 展示资源
	{
		//—— 程序化网格 ——
		uint64_t 球 = 0;
		uint64_t 圆柱 = 0;
		uint64_t 圆锥 = 0;
		uint64_t 胶囊 = 0;
		uint64_t 圆环 = 0;
		uint64_t 平面 = 0;
		uint64_t 地面 = 0;
		//反向绕序地面（用于确认引擎的正面绕序；仅一个会可见）
		uint64_t 地面反向 = 0;
		uint64_t 圆盘 = 0;
		uint64_t 立方体 = 0;
		uint64_t 四棱锥 = 0;
		//正二十面体球（卡通渲染区专用，纯三角面拓扑）
		uint64_t 卡通球 = 0;
		//水平细分网格（展区①的细分地形底板）
		uint64_t 地形 = 0;
		//三角形（图元清单补全）
		uint64_t 三角 = 0;
		//带子网格分段的四边形（第四百一十六轮；展区⑩ 多材质面板用，两段各一个三角形）
		uint64_t 分段平面 = 0;

		//—— 纹理 ——
		uint64_t 棋盘 = 0;
		//地板网格纹理（地面与展区地台共用）
		uint64_t 地板 = 0;
		uint64_t 法线贴图 = 0;
		uint64_t 粗糙贴图 = 0;
		uint64_t 天空 = 0;
		uint64_t 动态贴图 = 0;
		//自发光 / 环境光遮蔽 / 金属度贴图（材质贴图扩展展区）
		uint64_t 自发光贴图 = 0;
		uint64_t 遮蔽贴图 = 0;
		uint64_t 金属贴图 = 0;
		//3D LUT 查找表（17³ 暖调）
		uint64_t 查找表 = 0;

		//—— 材质 ——
		uint64_t 地面材质 = 0;
		uint64_t 贴图材质 = 0;
		//加法混合材质（卡通区光晕专用）
		uint64_t 光晕材质 = 0;
		//清漆层材质（材质展区对比专用）
		uint64_t 清漆材质 = 0;
		//镂空材质（Alpha 裁剪 ＋ UV 旋转）
		uint64_t 镂空材质 = 0;
		//贴图扩展材质（自发光 / AO / 金属度贴图 ＋ UV 缩放）
		uint64_t 扩展材质 = 0;
		/*
		逐物体卡通材质（第四百一十一轮；展区⑦ 三个不同档位）
		甲 = 二值化（色阶 1）、乙 = 三档 ＋ 边缘光、丙 = 不量化 ＋ 强边缘光；
		三者都带 tint 以保留原有配色。
		*/
		uint64_t 卡通材质甲 = 0;
		uint64_t 卡通材质乙 = 0;
		uint64_t 卡通材质丙 = 0;
		//多材质分段的两个材质（第四百一十一轮；展区⑩ 红 / 蓝两块）
		uint64_t 分段材质甲 = 0;
		uint64_t 分段材质乙 = 0;
		/*
		双面材质（顶面与背面都可见；展区① 的平面 / 圆盘 / 三角三类二维图元专用）
		二维图元在环形排布中侧看只剩一条薄片，背面又被剔除，故统一改用关闭背面剔除的管线。
		*/
		uint64_t 双面材质 = 0;

		//—— 后处理管线（全部为同一顶点着色器 `后处理.vert.spv`） ——
		uint64_t 亮部提取 = 0;
		uint64_t 模糊 = 0;
		uint64_t 暗角 = 0;
		uint64_t 平滑 = 0;
		uint64_t 色彩查找 = 0;
		uint64_t 遮蔽 = 0;
		uint64_t 色调映射 = 0;
		uint64_t 深度描边 = 0;
		uint64_t 体积雾 = 0;
		uint64_t 体积光 = 0;
		uint64_t 反射 = 0;

		//—— 字体 ——
		uint64_t 字体 = 0;

		//—— 中间目标（同帧后处理链轮转；与交换链同尺寸） ——
		uint64_t 目标甲 = 0;
		uint64_t 目标乙 = 0;
		uint32_t 目标宽 = 0;
		uint32_t 目标高 = 0;

		//—— 场景配置快照（第五百三十一轮：进区③ 切换簇光照后按当前相机重新登记光源） ——
		Light_Data 光照配置;
		Fog_Data 雾配置;
	};

	/*
	展示状态（相机 ＋ 动画时钟 ＋ 各展区的全局开关状态）
	进区开关只在状态变化时上门面，避免逐帧重复设置。
	*/
	struct 展示状态
	{
		//相机世界位置
		float 位置[3] = { 0.0f, 9.5f, 14.0f };
		//偏航 / 俯仰（弧度）
		float 偏航 = 0.0f;
		float 俯仰 = -0.26f;
		//累计秒（驱动动画）
		float 累计秒 = 0.0f;
		//动态贴图上次更新时间（秒；负数表示尚未更新）
		float 上次更新时间 = -1.0f;
		//卡通渲染区是否激活（色阶量化 ＋ 边缘光 ＋ 暗部色调 ＋ 卡通高光 ＋ 外扩描边）
		bool 卡通区激活 = false;
		//Cluster 灯墙区是否激活
		bool 灯墙区激活 = false;
		//光照阴影区（展区③）是否激活（进入开簇光照以容纳 8 盏聚光 ＋ 3 盏点光）
		bool 光照阴影区激活 = false;
		//粒子喷泉区激活 / 已配置 / 是否走常驻路径
		bool 粒子区激活 = false;
		bool 粒子已配置 = false;
		bool 粒子常驻 = false;
		//当前生效的后处理区编号（0 = 未在任何后处理区；展区⑫–⑰）
		uint32_t 后处理区 = 0;
		//SSAA / MSAA 对比区是否激活（展区⑱）
		bool 采样区激活 = false;
		//雾模式区当前档（0 = 默认线性雾；展区⑲内 0/1/2 轮换）
		uint32_t 雾档 = 0;
		//多线程区是否激活（展区㉑：区内 4 线程、区外 0）
		bool 线程区激活 = false;
		//正交投影区是否激活（展区㉒）
		bool 正交区激活 = false;
		//聚光灯阴影模式（true = 前 8 盏各自投影，false = 单盏；K 键切换）
		bool 聚光多盏 = true;
		//已提交给渲染器的聚光灯阴影模式（避免逐帧重复设置）
		bool 聚光多盏已提交 = true;
	};

	/*
	能力展示场景
	生命周期：init(渲染器) → 每帧 update(渲染器, 输入, 秒) ＋ frame_draw(渲染器) → shutdown(渲染器)
	init 失败返回 false（资源创建失败），调用方应退出展示模式。
	*/
	class 能力展示场景
	{
	public:
		//搭建场景与全部资源，并应用初始相机与光照
		bool init(Renderer& 渲染器);
		//按输入推进相机（秒为帧间隔）并在窗口尺寸变化时重建后处理目标
		void update(Renderer& 渲染器, const 展示输入& 输入, float 秒);
		/*
		探测 / 跳转用：直接设置相机位姿
		仅写内部状态（位置 / 偏航 / 俯仰），真正的渲染器相机与进区开关由随后的 update 提交；
		俯仰钳到 ±1.35 弧度，离地高度不低于 0.6（与 update 同口径）。
		*/
		void 相机位姿设置(const float 位置[3], float 偏航值, float 俯仰值);
		//登记本帧全部绘制项与字幕（真正绘制在 frame_render 内发生）
		void frame_draw(Renderer& 渲染器);
		//释放全部资源（幂等）
		void shutdown(Renderer& 渲染器);

		//相机世界位置（Overlay 显示用）
		void 相机位置(float 出[3]) const;
		//当前偏航 / 俯仰（弧度；Overlay 显示用）
		float 偏航(void) const;
		float 俯仰(void) const;
		//当前聚光灯阴影模式（true = 八盏各自投影；Overlay 显示用）
		bool 聚光多盏(void) const;
		//切换聚光灯阴影模式（在 update 里提交给渲染器）
		void 聚光多盏切换(void);
		//展区数量与标题（Overlay 图例用；标题以「①」「②」…开头）
		uint32_t 展区数量(void) const;
		const char* 展区标题(uint32_t 序号) const;

	private:
		//资源台账与运行状态
		展示资源 资源_;
		展示状态 状态_;
	};
}
